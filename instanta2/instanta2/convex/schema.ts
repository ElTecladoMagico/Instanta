// convex/schema.ts
import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";

export default defineSchema({
  // Table to store user information
  users: defineTable({
    // using Clerk for authentication we store the userId and the email
    userId: v.string(), 
    email: v.string(),
    name: v.optional(v.string()),
  }).index("by_userId", ["userId"]),

  // Table for each payment button a user creates
  buttons: defineTable({
    userId: v.id("users"), // Relation to the 'users' table
    amount: v.number(),
    toAddress: v.string(),
    currency: v.string(),
    title: v.string(),
    // We could add other button-specific settings here
  }).index("by_userId", ["userId"]),

  // Table to record each payment attempt
  // Payments relate both the buttons and the users
  payments: defineTable({
    buttonId: v.id("buttons"), // Relation to the 'buttons' table
    userId: v.id("users"), // Relation to the 'users' table
    paymentId: v.string(), // The unique 'pay_...' ID generated by the client
    status: v.union( // A payment can only be in one of these states
      v.literal("pending"),
      v.literal("confirmed"),
      v.literal("failed")
    ),
    txHash: v.optional(v.string()), // The blockchain transaction hash
  })
    .index("by_buttonId", ["buttonId"])
    .index("by_userId", ["userId"])
    .index("by_paymentId", ["paymentId"]),
});